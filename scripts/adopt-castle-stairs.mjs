import assert from 'node:assert/strict';
import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root='output/model-generation/models/valley-castle';
const source=`${root}/work/low-poly/candidate-08/candidate.glb`;
const json=async p=>JSON.parse(await readFile(p,'utf8'));
const save=(p,v)=>writeFile(p,JSON.stringify(v,null,2)+'\n');
const bytes=await readFile(source),sha256=createHash('sha256').update(bytes).digest('hex');
const review=await json('assets/castle-stairs/adoption-review.json');
const inspection=await json(`${root}/qa/revision-08-inspection.json`);
assert.equal(review.decision,'adopt');assert.equal(review.sha256,sha256);
assert.equal(inspection.validation,'passed');assert.equal(inspection.sha256,sha256);
const qa=await json('output/playwright/castle-stairs/summary.json');
assert.equal(qa.sha256,sha256);assert.deepEqual(qa.errors,[]);assert.equal(qa.participants,5);
await mkdir('assets/castle-stairs',{recursive:true});
for(const name of ['stairs-mesh-verification.json','revision-08-inspection.json'])
  await copyFile(`${root}/qa/${name}`,`assets/castle-stairs/${name}`);
await copyFile('output/playwright/castle-stairs/summary.json','assets/castle-stairs/game-qa.json');
const manifest=await json('public/models/valley-castle/asset.json');
Object.assign(manifest,{sha256,bytes:bytes.length,triangles:inspection.triangles,revision:'08'});
Object.assign(manifest.provenance,{candidateFile:source,visualReview:'assets/castle-stairs/adoption-review.json'});
manifest.notes+=' Revision 08 retains 0.8m more of the original floor at the entrance stair landing for the giant ape.';
const world=await json('public/models/world-assets.json');
world.assets[world.assets.findIndex(a=>a.modelKey==='valley-castle')]=manifest;
const catalog=await json('assets/world-models.json');
Object.assign(catalog.assets.find(a=>a.key==='valley-castle'),{sha256});
await copyFile(source,'public/models/valley-castle/model.glb');
await save('public/models/valley-castle/asset.json',manifest);
await save('public/models/world-assets.json',world);
await save('assets/world-models.json',catalog);
const request=await json('assets/valley-castle-request.json');
request.history.push({revision:request.revision,sha256:request.sha256,status:'preserved-before-stair-landing-fix'});
Object.assign(request,{revision:'08',sha256,rollout:'local-assets-updated-server-restart-pending',stairsQA:'assets/castle-stairs/game-qa.json'});
await save('assets/valley-castle-request.json',request);
console.log(JSON.stringify({sha256,bytes:bytes.length,triangles:inspection.triangles}));
