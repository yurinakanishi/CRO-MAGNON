import {readFile,writeFile} from 'node:fs/promises';
const revision=process.argv[2]??'08';
if(!/^\d{2}$/.test(revision))throw new Error('Invalid revision');
const path=`output/model-generation/models/valley-castle/qa/walk-rev${revision}.json`;
const data=JSON.parse(await readFile(path,'utf8'));
await writeFile('shared/castle-surface-data.mts',`// Generated by scripts/install-castle-surface.mjs from the exact revision ${revision} GLB.\nexport const CASTLE_SURFACE_DATA=${JSON.stringify(data)};\n`);
